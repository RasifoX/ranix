#!/bin/sh
# .config -> include/generated/autoconf.h (C) + include/generated/auto.conf (Make).
# Lines are KEY=value or "# CONFIG_X is not set". y/n are booleans: enabled emits
# "#define CONFIG_X 1", disabled emits nothing so IS_ENABLED()/#ifdef see it off.
# Ints and "strings" pass through. The Make fragment carries every key (including
# =n) so the Makefile can filter sources on CONFIG_x.
config="$1"
out_h="$2"
out_mk="$3"

mkdir -p "$(dirname "$out_h")" "$(dirname "$out_mk")"

{
	echo "/* generated by scripts/genconfig.sh from $config — do not edit */"
	echo "#ifndef KERNEL_GENERATED_AUTOCONF_H"
	echo "#define KERNEL_GENERATED_AUTOCONF_H"
} > "$out_h"
: > "$out_mk"

while IFS= read -r line || [ -n "$line" ]; do
	case "$line" in
	'# '*' is not set')
		key=$(echo "$line" | sed -n 's/^# \(CONFIG_[A-Za-z0-9_]*\) is not set$/\1/p')
		[ -n "$key" ] && echo "$key=n" >> "$out_mk"
		;;
	CONFIG_*=*)
		key=${line%%=*}
		val=${line#*=}
		echo "$line" >> "$out_mk"
		case "$val" in
		y) echo "#define $key 1" >> "$out_h" ;;
		n) : ;;
		*) echo "#define $key $val" >> "$out_h" ;;
		esac
		;;
	esac
done < "$config"

echo "#endif" >> "$out_h"
