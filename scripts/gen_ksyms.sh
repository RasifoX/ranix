#!/bin/sh
# Emit a C symbol table (address -> name, sorted) plus build identity from a
# linked kernel ELF, for in-kernel panic symbolization. Function addresses live
# in .text, which precedes the .rodata this table lands in, so they stay valid
# across the relink that adds this object.
elf="$1"
arch="$2"
git=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
dirty=$(git diff --quiet 2>/dev/null || echo +)
date=$(date +%Y-%m-%d)

echo "/* generated by scripts/gen_ksyms.sh — do not edit */"
echo "const char ranix_version[]   = \"0.9.0\";"
echo "const char ranix_gitrev[]    = \"${git}${dirty}\";"
echo "const char ranix_builddate[] = \"${date}\";"
echo "const char ranix_arch[]      = \"${arch}\";"

llvm-nm -n "$elf" | awk '
	BEGIN { n = 0 }
	NF == 3 && $1 ~ /^[0-9a-fA-F]+$/ && $2 ~ /^[Tt]$/ && $3 ~ /^[A-Za-z_]/ { addr[n]=$1; name[n]=$3; n++ }
	END {
		print "const unsigned long ksym_count = " n ";";
		printf "const unsigned long ksym_addrs[] = {";
		for (i = 0; i < n; i++) printf "0x%s,", addr[i];
		print "};";
		printf "const char *const ksym_names[] = {";
		for (i = 0; i < n; i++) printf "\"%s\",", name[i];
		print "};";
	}
'
