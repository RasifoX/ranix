#define FONT_EXT_COUNT ((int)(sizeof(font_ext)/sizeof(font_ext[0])))

static inline const u8 *font_lookup(u32 cp)
{
    if (cp >= 32 && cp <= 127) return font8x16[cp - 32];
    for (int i = 0; i < FONT_EXT_COUNT; i++)
        if (font_ext[i].cp == cp) return font_ext[i].g;
    return font8x16['?' - 32];
}

